#!/usr/bin/env node
// Encodes the raw captures of the product (.marketing-raw, written by e2e/marketing) into the
// images of the public site: AVIF and WebP, several widths, both themes, in public/marketing, and
// their sizes in src/features/marketing/lib/previews.generated.ts (width and height attributes,
// no layout shift). Same input, same bytes: the encoders run without randomness.
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import sharp from 'sharp';
import { fileName, FORMATS, PREVIEW_IDS, SCALE, THEMES, widthsOf } from './marketing-previews.mjs';

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const raw = join(webRoot, '.marketing-raw');
const output = join(webRoot, 'public/marketing');

const ENCODERS = {
  avif: (image) => image.avif({ quality: 55, effort: 6, chromaSubsampling: '4:4:4' }),
  webp: (image) => image.webp({ quality: 80, effort: 6, smartSubsample: true }),
};

/** One image of a capture: its width and its format. The same capture gives the same bytes. */
export function encodePreview(source, width, format) {
  return ENCODERS[format](sharp(source).resize({ width })).toBuffer();
}

async function main() {
  const sizes = {};
  await rm(output, { recursive: true, force: true });
  await mkdir(output, { recursive: true });
  for (const id of PREVIEW_IDS) {
    for (const theme of THEMES) {
      const source = await readFile(join(raw, `${id}-${theme}.png`));
      const meta = await sharp(source).metadata();
      // CSS pixels: the capture is SCALE times denser.
      const cssWidth = Math.round(meta.width / SCALE);
      const cssHeight = Math.round(meta.height / SCALE);
      if (theme === 'light') sizes[id] = { width: cssWidth, height: cssHeight };
      for (const width of widthsOf(meta.width)) {
        for (const format of FORMATS) {
          await writeFile(
            join(output, fileName(id, theme, width, format)),
            await encodePreview(source, width, format),
          );
        }
      }
    }
  }
  const source = `// Generated by scripts/marketing-encode.mjs (pnpm marketing:captures). Do not edit.
/** Size of each preview in CSS pixels, and the widths written in public/marketing. */
export const PREVIEW_SIZES = ${JSON.stringify(
    Object.fromEntries(
      Object.entries(sizes).map(([id, size]) => [
        id,
        { ...size, widths: widthsOf(size.width * SCALE) },
      ]),
    ),
    null,
    2,
  )} as const;
`;
  const target = join(webRoot, 'src/features/marketing/lib/previews.generated.ts');
  await writeFile(
    target,
    await format(source, { ...(await resolveConfig(target)), filepath: target }),
  );
  process.stdout.write(`Previews written: ${PREVIEW_IDS.length * THEMES.length} captures.\n`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
